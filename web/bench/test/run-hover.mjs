import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs'
import fs from 'fs'
const mock = fs.readFileSync(new URL('./mock.js', import.meta.url), 'utf8')
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const p = await (await b.newContext({ viewport: { width: 1500, height: 950 } })).newPage()
p.on('pageerror', e => console.log('PAGEERROR', e.message))
await p.addInitScript(mock)
await p.goto('http://localhost:8765/index.html'); await p.waitForSelector('.projbtn .ptitle'); await p.waitForTimeout(2500)
await p.click('.view[data-view=canvas] .toolbar button:has-text("%")'); await p.waitForTimeout(300)
// pan so the menu frame is in view
const fr = p.locator('.frm').nth(1); const bb = await fr.boundingBox()
const cv = await p.locator('.cv').boundingBox()
await p.mouse.move(cv.x + 20, cv.y + 20); await p.mouse.down(); await p.mouse.move(cv.x + 20 - (bb.x - cv.x - 40), cv.y + 20 - (bb.y - cv.y - 40), { steps: 5 }); await p.mouse.up(); await p.waitForTimeout(300)
const b2 = await fr.boundingBox()
await p.mouse.move(b2.x + 60, b2.y + 30 + 125); await p.waitForTimeout(300)
await p.screenshot({ path: 'test/h1.png', clip: { x: b2.x - 10, y: b2.y - 10, width: 400, height: 330 } })
await p.click('.seg.modes button[data-m=comment]'); await p.waitForTimeout(200)
await p.mouse.move(b2.x + 200, b2.y + 30 + 200); await p.mouse.move(b2.x + 210, b2.y + 30 + 205); await p.waitForTimeout(300)
await p.screenshot({ path: 'test/h2.png', clip: { x: b2.x - 10, y: b2.y - 10, width: 400, height: 330 } })
await b.close()
