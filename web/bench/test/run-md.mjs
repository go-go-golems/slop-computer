import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs'
import fs from 'fs'
const mock = fs.readFileSync(new URL('./mock.js', import.meta.url), 'utf8')
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const p = await (await b.newContext({ viewport: { width: 1500, height: 950 } })).newPage()
p.on('pageerror', e => console.log('PAGEERROR', e.message))
await p.addInitScript(mock)
await p.goto('http://localhost:8765/index.html'); await p.waitForSelector('.projbtn .ptitle'); await p.waitForTimeout(2000)
await p.fill('.composer textarea', 'Fix the overflow'); await p.press('.composer textarea', 'Enter')
await p.waitForFunction(() => !document.querySelector('.pill.busy'), null, { timeout: 30000 }); await p.waitForTimeout(500)
console.log(await p.evaluate(() => { const md = document.querySelector('.msg.agent .md'); return { tags: [...md.children].map(c => c.tagName).join(','), refs: [...md.querySelectorAll('.fref')].map(r => r.dataset.file + ':' + r.dataset.line) } }))
console.log('guide tail:', await p.evaluate(() => window.__lastPrompt.length))
await p.click('.msg.agent .md .fref >> nth=1'); await p.waitForTimeout(500)
console.log('code opened:', await p.evaluate(() => document.querySelector('.efoot')?.innerText.split('\n')[0]))
await p.locator('.msg.agent').last().screenshot({ path: 'test/md.png' })
await b.close()
