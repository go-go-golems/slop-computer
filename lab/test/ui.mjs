import { chromium } from 'playwright';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const root = process.argv[2] || 'dist', shots = process.argv[3] || 'test/shots';
fs.mkdirSync(shots, { recursive: true });
const types = { '.html': 'text/html', '.js': 'text/javascript', '.wasm': 'application/wasm', '.css': 'text/css' };
const srv = http.createServer((q, r) => { const u = decodeURIComponent(q.url.split('?')[0]); const p = path.join(root, u === '/' ? 'index.html' : u); if (!fs.existsSync(p)) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'content-type': types[path.extname(p)] || 'application/octet-stream' }); fs.createReadStream(p).pipe(r); }).listen(0);
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } }); const pg = await ctx.newPage();
const errs = [];
pg.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(`${m.type()}: ${m.text()}`); });
pg.on('pageerror', e => errs.push('pageerror: ' + e.message));
const t0 = Date.now();
await pg.goto(`http://127.0.0.1:${srv.address().port}/`);
await pg.waitForSelector('.bar', { timeout: 30000 });
console.log('shell up in', Date.now() - t0, 'ms');
const shot = async (n) => { await pg.waitForTimeout(500); await pg.screenshot({ path: `${shots}/${n}.png` }); console.log('shot', n); };
const tab = (name) => pg.locator('.dtab .lbl', { hasText: new RegExp('^' + name) }).first().click();
await shot('01-start');
await tab('Site');
const fr = pg.frameLocator('.frame iframe').first();
await fr.locator('#posts li h3').first().waitFor({ timeout: 15000 });
console.log('posts:', await fr.locator('#posts li h3').allTextContents());
await shot('02-site');
// draft + publish as Ramon, with Ana beside
await pg.locator('.proj .projbtn').click(); await pg.locator('.proj .menu button', { hasText: 'Ramon' }).click();
await pg.locator('.toolbar select[aria-label="Second frame"]').selectOption('gst_ana');
await pg.waitForTimeout(1200);
const f1 = pg.frameLocator('.frame iframe').nth(0);
await f1.locator('#title').fill('Hello from the lab');
await f1.locator('#body').fill('Written by Ramon in a sandboxed frame.');
await f1.locator('#draft button').click();
await f1.locator('#drafts button[data-pub]').first().waitFor({ timeout: 8000 });
console.log('drafts:', await f1.locator('#drafts li b').allTextContents());
await f1.locator('#drafts li', { hasText: 'Hello from the lab' }).locator('button[data-pub]').click();
await pg.waitForTimeout(800);
const f2 = pg.frameLocator('.frame iframe').nth(1);
console.log('ana sees:', await f2.locator('#posts li h3').allTextContents(), '| ana stats:', await f2.locator('#stats').textContent(), '| ana compose hidden:', await f2.locator('#compose').isHidden());
await shot('03-site-two');
await tab('Turns');
await pg.locator('.trow').first().click();
await shot('04-turns');
await tab('Console');
const cin = pg.locator('.conin input');
for (const l of ['sql blog "SELECT title, status, author FROM posts"', 'sql blog "DELETE FROM posts"', 'can gst_ana blog sql.admin']) { await cin.fill(l); await cin.press('Enter'); await pg.waitForTimeout(300); }
await shot('05-console');
await tab('Access');
await shot('06-access');
await tab('Data');
await pg.locator('.listnav button', { hasText: 'posts' }).first().click();
await shot('07-data');
await tab('Code');
await pg.waitForTimeout(400);
await shot('08-code');
await tab('Actor');
await shot('09-actor');
await tab('Agent');
await shot('10-agent');
await tab('Stores');
await shot('11-stores');
// tracker: create a store via mount as Kim
await pg.locator('.proj .projbtn').click(); await pg.locator('.proj .menu button', { hasText: 'Kim' }).click();
await tab('Site');
await pg.locator('.toolbar select[aria-label="Second frame"]').selectOption('');
await pg.locator('.addrform input').fill('site.lab/t/kims-board'); await pg.locator('.addrform button').click();
await pg.locator('.frame .btn.primary', { hasText: 'Create' }).click({ timeout: 8000 });
const tf = pg.frameLocator('.frame iframe').first();
await tf.locator('#text').waitFor({ timeout: 8000 });
await tf.locator('#text').fill('First card on Kim\'s board'); await tf.locator('#add button').click();
await pg.waitForTimeout(600);
console.log('kim cards:', await tf.locator('.card .t').allTextContents());
await shot('12-tracker');
console.log('errors:', errs.slice(0, 20));
await b.close(); srv.close();
