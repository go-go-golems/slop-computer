// tsnotes is the fixture app (testdata/tsnotes): a TypeScript page and
// actor that share a contract in api.ts.
func tsnotes(t *testing.T) map[string]string {
	t.Helper()
	out := map[string]string{}
	root := filepath.Join("testdata", "tsnotes")
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := os.ReadFile(p)
		rel, _ := filepath.Rel(root, p)
		out[filepath.ToSlash(rel)] = string(b)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	for name, b := range client.Tsconfigs("actor.ts", false) {
		out[name] = string(b)
	}
	return out
}

// tscPath is TypeScript's tsc: SLOP_TSC, or web/runtime's (make runtime,
// or npm install --prefix web/runtime as make test-ci does).
func tscPath() string {
	if p := os.Getenv("SLOP_TSC"); p != "" {
		return p
	}
	p := filepath.Join("..", "..", "web", "runtime", "node_modules", "typescript", "bin", "tsc")
	if _, err := os.Stat(p); err != nil {
		return ""
	}
	abs, _ := filepath.Abs(p)
	return abs
}

// The declarations an app gets (app.types), and the fixture app checked
// against them with tsc (SLOP3-024, design §5): its two programs pass, and
// mistakes on either side of its contract are type errors. The same files,
// generated tsconfigs included, compile and run on the server.
func TestAppTypes(t *testing.T) {
	h := newHarness(t)
	admin := h.tokenFor("admin@example.com", "read", "write", "admin")
	app := tsnotes(t)
	h.call(admin, "store.new", map[string]any{"id": "tsnotes"})
	h.push(admin, map[string]any{"store": "tsnotes", "files": files(app)})

	types := func() map[string]string {
		out := map[string]string{}
		res := h.call(admin, "app.types", map[string]any{"app": "tsnotes"}).(map[string]any)
		for _, f := range res["files"].([]any) {
			m := f.(map[string]any)
			out[m["path"].(string)] = m["text"].(string)
		}
		return out
	}
	// Before the grant, workshop is not the app's to use: not declared.
	if mods := types()["modules.d.ts"]; strings.Contains(mods, "workshop") || !strings.Contains(mods, `yaml: typeof import("yaml")`) {
		t.Fatalf("modules.d.ts before the grant:\n%s", mods)
	}
	h.call(admin, "app.trust", map[string]any{"app": "tsnotes", "module": "workshop"})
	decl := types()
	for name, want := range map[string]string{
		"page.d.ts":    "declare const claude: import(\"slop:page/types\").Claude;",
		"actor.d.ts":   "declare function defineActor<D extends ActorDef>(def: D): D;",
		"modules.d.ts": "workshop: WorkshopModule;",
	} {
		if !strings.HasPrefix(decl[name], "// Generated by slop (app.types) for tsnotes at main") || !strings.Contains(decl[name], want) {
			t.Fatalf("%s lacks %q:\n%.400s", name, want, decl[name])
		}
	}

	// On the server: the actor compiles (with the generated tsconfigs) and runs.
	add := h.call(admin, "actor.call", map[string]any{"store": "tsnotes", "action": "add", "args": map[string]any{"text": "hello"}}).(map[string]any)
	list := h.call(admin, "actor.call", map[string]any{"store": "tsnotes", "action": "list", "args": map[string]any{}}).([]any)
	if num(add["id"]) != 1 || len(list) != 1 || list[0].(map[string]any)["text"] != "hello" {
		t.Fatalf("add %v, list %v", add, list)
	}

	tsc := tscPath()
	if tsc == "" {
		t.Skip("no tsc (make runtime, or SLOP_TSC=…/typescript/bin/tsc): the fixture is not type-checked")
	}
	dir := t.TempDir()
	write := func(files map[string]string) {
		for p, text := range files {
			full := filepath.Join(dir, filepath.FromSlash(p))
			if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(full, []byte(text), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	// Reactors, type-checked only (following the system log needs the
	// system module): a system: key gets a system log entry, which has no
	// store; any other key a commit of the store's log.
	const reactors = `export const on: Reactors = {
  'table:notes'(ctx, commit) { return commit.store + commit.epoch },
  'system:grant'(ctx, entry) { return entry.rev + (entry.summary ?? '') },
}
`
	write(app)
	write(map[string]string{"server/reactors.ts": reactors})
	for name, text := range decl {
		write(map[string]string{client.TypesDir + "/" + name: text})
	}
	check := func(project string) (string, bool) {
		out, err := exec.Command("node", tsc, "-p", filepath.Join(dir, project)).CombinedOutput()
		return string(out), err == nil
	}
	for _, p := range []string{"tsconfig.json", "tsconfig.actor.json"} {
		if out, ok := check(p); !ok {
			t.Fatalf("tsc -p %s:\n%s", p, out)
		}
	}
	// Mistakes on each side of the contract.
	write(map[string]string{
		"main.ts": strings.Replace(app["main.ts"], "{ text: 'from the page' }", "{ txt: 'from the page' }", 1),
		"actor.ts": strings.Replace(strings.Replace(app["actor.ts"], "return { id: lastRowid }", "return { id: String(lastRowid) }", 1),
			"use('workshop')", "use('system')", 1),
		"server/reactors.ts": strings.Replace(reactors, "entry.rev", "entry.store", 1),
	})
	pages, okPages := check("tsconfig.json")
	actorOut, okActor := check("tsconfig.actor.json")
	if okPages || !strings.Contains(pages, "'txt' does not exist") {
		t.Errorf("the page's mistake:\n%s", pages)
	}
	if okActor || !strings.Contains(actorOut, `"system"' is not assignable`) || !strings.Contains(actorOut, "Type 'string' is not assignable to type 'number'") ||
		!strings.Contains(actorOut, "Property 'store' does not exist on type 'SystemEntry'") {
		t.Errorf("the actor's mistakes:\n%s", actorOut)
	}
}
