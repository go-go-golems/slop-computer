var update = flag.Bool("update", false, "rewrite the golden files")

type tsNested struct {
	Path string `json:"path" jsonschema_description:"where it is"`
	Size int64  `json:"size,omitempty"`
}

type tsIn struct {
	Store   string            `json:"store" jsonschema_description:"the store"`
	Level   string            `json:"level,omitempty" jsonschema:"enum=view,enum=interact" jsonschema_description:"the level, if any"`
	Files   []tsNested        `json:"files"`
	Tags    map[string]int    `json:"tags,omitempty"`
	Raw     []byte            `json:"raw,omitempty"`
	Any     any               `json:"any,omitempty"`
	Kinds   List              `json:"kinds,omitempty"`
	Header  map[string]string `json:"x-header,omitempty" jsonschema_description:"a name TypeScript must quote"`
	Comment string            `json:"comment,omitempty" jsonschema_description:"says */ in its text"`
}

type tsOut struct {
	N     int64      `json:"n"`
	Files []tsNested `json:"files"`
	Prev  *tsNested  `json:"prev,omitempty"`
}

// The converter's output, one type per case, against
// testdata/typescript.golden.ts (go test ./pkg/verbs -run TestTypeScript -update
// rewrites it). The fixture app's check runs tsc on the file.
func TestTypeScript(t *testing.T) {
	cases := []struct {
		name string
		s    *jsonschema.Schema
	}{
		{"Input", schemaOf(reflect.TypeFor[tsIn]())},
		{"Output", outputSchema(reflect.TypeFor[tsOut]())},
		{"OutputList", outputSchema(reflect.TypeFor[[]tsOut]())},
		{"Untyped", schemaOf(reflect.TypeFor[any]())},
		{"Map", outputSchema(reflect.TypeFor[map[string]any]())},
		{"Union", &jsonschema.Schema{OneOf: []*jsonschema.Schema{
			object([]string{"path", "text"}, "path", &jsonschema.Schema{Type: "string"}, "text", &jsonschema.Schema{Type: "string"}),
			object([]string{"path", "delete"}, "path", &jsonschema.Schema{Type: "string"}, "delete", &jsonschema.Schema{Const: true}),
		}}},
		{"Tuple", &jsonschema.Schema{Type: "array", PrefixItems: []*jsonschema.Schema{{Type: "string"}, {Type: "integer"}}}},
		{"ArrayOfUnion", &jsonschema.Schema{Type: "array", Items: &jsonschema.Schema{OneOf: []*jsonschema.Schema{{Type: "string"}, {Type: "integer"}}}}},
		{"Ref", &jsonschema.Schema{Ref: "#/$defs/x"}},
		{"UnknownAbsorbs", &jsonschema.Schema{AnyOf: []*jsonschema.Schema{{Type: "string"}, {}}}},
	}
	var b strings.Builder
	b.WriteString("// Generated by TestTypeScript (pkg/verbs): the JSON Schema converter's output.\nexport {};\n")
	for _, c := range cases {
		b.WriteString("\ntype " + c.name + " = " + TypeScript(c.s, "") + ";\n")
	}
	got := b.String()
	const golden = "testdata/typescript.golden.ts"
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(golden, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("%v (go test -run TestTypeScript -update writes it)", err)
	}
	if got != string(want) {
		t.Fatalf("the converter's output changed (-update rewrites %s):\n%s", golden, got)
	}
}

func TestTypeScriptObjectMembers(t *testing.T) {
	s := schemaOf(reflect.TypeFor[tsNested]())
	got := TypeScriptObjectMembers(s, "  ", nil, map[string]bool{"path": true})
	want := "  /** where it is */\n  path?: string;\n  size?: number;\n"
	if got != want {
		t.Fatalf("members:\n%q\nwant\n%q", got, want)
	}
	if got := TypeScriptObjectMembers(s, "", map[string]bool{"size": true}, nil); got != "/** where it is */\npath: string;\n" {
		t.Fatalf("skipping size: %q", got)
	}
}

// object is an object schema with properties name, schema, … in order.
func object(required []string, kv ...any) *jsonschema.Schema {
	s := &jsonschema.Schema{Type: "object", Properties: jsonschema.NewProperties(), Required: required}
	for i := 0; i < len(kv); i += 2 {
		s.Properties.Set(kv[i].(string), kv[i+1].(*jsonschema.Schema))
	}
	return s
}
