'use strict';
// Experiment 2: immutability, chaining, diagnostics, fragments, slots, app().
// node exp2-grammar.js <apps/pinboard>
const { load, J } = require('./harness.js');
const { PB } = load(process.argv[2]);
const { ui } = PB;
const t = (name, fn) => { try { const v = fn(); console.log(name + ': ok ' + (typeof v === 'string' ? v : J(v))); } catch (e) { console.log(name + ': THROWS ' + e.constructor.name + ': ' + e.message); } };

console.log('--- immutability');
const s = ui.stack(ui.text('a'));
const s2 = s.pad(8);
t('pad returns a new builder; old unchanged', () => [s.props.pad, s2.props.pad, s === s2]);
t('assigning a property', () => { s.kind = 'row'; return s.kind; });
t('Object.isFrozen(props/children/handlers)', () => [Object.isFrozen(s.props), Object.isFrozen(s.children), Object.isFrozen(s.handlers), Object.isFrozen(s.attrs)]);
t('props is shallow-frozen: style object stays mutable', () => { const b = ui.text('x').style({ color: 'red' }); b.props.style.color = 'blue'; return b.props.style.color; });
t('delete through the proxy (no deleteProperty trap)', () => { const b = ui.text('x'); delete b.kind; return b.kind === undefined ? 'kind deleted' : b.kind; });
t('attrs are shared by derived builders (_p keeps the same object)', () => { const a = ui.text('x').use(PB.fragments.taggable); const b = a.pad(4); b.attrs.tags.push('leak'); return [a.attrs === b.attrs, a.attrs.tags]; });
t('b.get(k) returns the live attr value', () => { const a = ui.text('x').use(PB.fragments.taggable).tag('one'); a.get('tags').push('two'); return a.attrs.tags; });
t('set(k, fn) copies attrs', () => { const a = ui.text('x').set('k', 1); const b = a.set('k', v => v + 1); return [a.attrs.k, b.attrs.k]; });
t('discarded result (guide ch.09 promises a warning)', () => { const b = ui.stack(); b.pad(8); return b.build().root.props; });
t('handlers accumulate per event', () => ui.button('x').on('click', () => 1).on('click', () => 2).handlers.click.length);
t('then/toJSON are undefined (not thenable)', () => [typeof s.then, typeof s.toJSON]);
t('JSON.stringify(builder) keys', () => Object.keys(JSON.parse(JSON.stringify(ui.text('x')))));
t('map must return a builder', () => ui.text('x').map(b => 3));
t('map returning a builder', () => ui.text('x').map(b => b.bold()).props);
t('kids(): strings/numbers become text, null/false dropped, arrays flattened', () => ui.row('a', 2, null, false, undefined, [ui.text('b'), ['c']]).children.map(c => c.kind + ':' + c.props.value));

console.log('--- diagnostics');
t('ui.stack().gap("big")', () => ui.stack().gap('big'));
t('ui.stack().gap("xl")', () => ui.stack().gap('xl').props.gap);
t('ui.stack().cols(3)', () => ui.stack().cols(3));
t('ui.stack(ui.text("a")).colums(3) (guide ch.09)', () => ui.stack(ui.text('a')).colums(3));
t('ui.text("x").tag("a") (taggable exists after board.js)', () => ui.text('x').tag('a'));
t('ui.text("x").bindd()', () => ui.text('x').bindd());
t('ui.text("x").zzzzzzzz()', () => ui.text('x').zzzzzzzz());
t('.on("click", "notfn")', () => ui.button('x').on('click', 'nope'));
t('.bind(3)', () => ui.text().bind(3));
t('ui.list(query, fn)', () => ui.list(PB.db.x, r => ui.text(r)));
t('ui.each(src) without fn', () => ui.each([]));
t('grid.cols("3")', () => ui.grid().cols('3'));
t('.menu("x")', () => ui.text('x').menu('x'));
t('fill without slot', () => ui.row(ui.text('a')).fill('body', ui.text('b')));
t('fill with slot', () => ui.row(ui.text('a'), ui.stack(ui.slot('body'))).fill('body', ui.text('b')).build().nodes.map(n => n.kind));
t('size("xl") (guide ch.03 uses it as a type size)', () => ui.text('n').size('xl').props);
t('text.cols via owners list', () => ui.text('n').placeholder('x'));
t('app("x").viw(...)', () => PB.app('x').viw(ui.text('a')));
t('app("x").view(c => …)', () => PB.app('x').view(c => ui.text('a')));
t('app("x").view("str")', () => PB.app('x').view('str'));
t('app("bad name")', () => PB.app('bad name'));
t('app("x").register() outside evalSource', () => PB.app('x').register());
t('app().state(3)', () => PB.app('x').state(3));
t('app().param.toggle("a", "yes").build().params', () => PB.app('x').param.toggle('a', 'yes').build().params);
t('app().param.slider twice with the same name (replaced)', () => PB.app('x').param.slider('a', 1).param.slider('a', 2).build().params);
t('app().state merges', () => PB.app('x').state({ a: 1 }).state({ b: 2 }).build().state);
t('app def frozen', () => Object.isFrozen(PB.app('x').build()));
t('app().menu accumulates', () => PB.app('x').menu([{ label: 'a' }]).menu(['-']).build().menu.length);
t('app("x").state({}).view(ui.text().bind(c => c.state.n)).build() (guide ch.09: undeclared state error)', () => Object.keys(PB.app('x').state({ m: 0 }).view(ui.text().bind(c => c.state.n)).build()));

console.log('--- fragments');
const tg = PB.fragments.taggable;
t('fragment registry names (after board.js and a seed)', () => Object.keys(PB.fragments));
t('taggable.toYAML()', () => tg.toYAML());
t('use + tag + hasTag query', () => { const b = ui.text('x').use(tg).tag('a', 'b').tag('a'); return [b.attrs.tags, b.hasTag('a'), b.hasTag('z'), b.frags.map(f => f.name)]; });
t('use by name', () => ui.text('x').use('taggable').frags.map(f => f.name));
t('use twice is a no-op', () => { const b = ui.text('x').use(tg); return b.use(tg) === b; });
t('use(unknown)', () => ui.text('x').use('nope'));
t('decorate runs at use time (taggable adds a strip)', () => (ui.text('x').use(tg).props.strip || []).length);
const hooked = PB.fragment('hooked').attr('n', 0).on('paste', (b) => { throw new Error('hook ran'); });
t('fragment .on(ev) hooks are stored, never called', () => [Object.keys(hooked.hooks), ui.text('x').use(hooked).attrs]);
PB.fragment('measured').method('size', (b, w, h) => b.set('w', w)).method('fancy', (b) => b.bold()).global();
t('global fragment: new method is on every builder', () => ui.text('x').fancy().props.bold);
t('global fragment cannot override a COMMON method (size)', () => ui.text('x').size(10, 20).props);
const f1 = PB.fragment('dupe').method('a', b => b.bold());
const f2 = PB.fragment('dupe').method('b', b => b.mono());
t('same fragment name twice: registry keeps the last; builders keep the object', () => [PB.fragments.dupe === f2, ui.text('x').use('dupe').frags[0] === f2]);
t('fragment attr default is cloned per use', () => { const a = ui.text('x').use(tg); const b = ui.text('y').use(tg); return a.attrs.tags === b.attrs.tags; });
t('fragment method on a builder without .use', () => ui.text('x').untag('a'));

